-- PASO 46 — PREINSCRIPCIONES (ficha de inscripción digital)
-- Ejecutar UNA vez en Supabase → SQL Editor (se puede repetir sin romper nada).
--
-- El estudiante completa la ficha en una página pública (preinscripcion.html, por link o QR),
-- elige un trayecto del ciclo con la inscripción abierta y descarga el PDF para imprimir y firmar.
-- Dirección, Regencia y Preceptoría la ven y corrigen; el docente (o suplente) del trayecto la ve en
-- solo lectura. Quien no es parte del personal NO puede leer nada: la página pública solo
-- puede (1) preguntar si la inscripción está abierta, (2) ver la lista de trayectos del ciclo
-- y (3) enviar una preinscripción. No existe ninguna forma de leer lo enviado desde afuera.
-- =====================================================================================

-- 1. Configuración: qué ciclo está abierto para preinscribirse --------------------------------
create table if not exists public.inscripcion_config (
  id          integer primary key default 1 check (id = 1),
  ciclo       integer not null default extract(year from now())::integer,
  abierta     boolean not null default false,
  mensaje     text check (char_length(mensaje) <= 300),
  actualizado timestamptz not null default now()
);
insert into public.inscripcion_config (id) values (1) on conflict (id) do nothing;

alter table public.inscripcion_config enable row level security;
drop policy if exists inscripcion_config_select on public.inscripcion_config;
drop policy if exists inscripcion_config_update on public.inscripcion_config;
create policy inscripcion_config_select on public.inscripcion_config for select to authenticated using (public.es_personal());
create policy inscripcion_config_update on public.inscripcion_config for update to authenticated using (public.es_personal()) with check (public.es_personal());

-- 2. Preinscripciones ---------------------------------------------------------------------------
create table if not exists public.preinscripciones (
  id               bigint generated by default as identity primary key,
  numero           text,
  ciclo            integer not null,
  trayecto_id      bigint references public.trayectos(id) on delete set null,
  estado           text not null default 'pendiente' check (estado in ('pendiente', 'confirmada', 'rechazada')),
  dni              text not null check (dni ~ '^[0-9]{6,9}$'),
  apellido         text not null check (char_length(apellido) between 1 and 80),
  nombre           text not null check (char_length(nombre) between 1 and 80),
  email            text check (email is null or char_length(email) <= 150),
  datos            jsonb not null default '{}'::jsonb,       -- todas las respuestas de la ficha
  nota_interna     text check (nota_interna is null or char_length(nota_interna) <= 500),
  created_at       timestamptz not null default now(),
  actualizado      timestamptz not null default now(),
  actualizado_por  uuid,
  confirmada_por   uuid,
  confirmada_en    timestamptz
);
create unique index if not exists preinscripciones_unica
  on public.preinscripciones (trayecto_id, dni) where estado <> 'rechazada';
create index if not exists preinscripciones_ciclo on public.preinscripciones (ciclo, estado);

alter table public.preinscripciones enable row level security;
drop policy if exists preinscripciones_select on public.preinscripciones;
drop policy if exists preinscripciones_update on public.preinscripciones;
drop policy if exists preinscripciones_delete on public.preinscripciones;
-- Ven: Dirección, Regencia y Preceptoría (es_personal) y el docente o suplente de ese trayecto
create policy preinscripciones_select on public.preinscripciones for select to authenticated
  using (public.es_personal() or public.es_docente_de(trayecto_id));
create policy preinscripciones_update on public.preinscripciones for update to authenticated
  using (public.es_personal()) with check (public.es_personal());
create policy preinscripciones_delete on public.preinscripciones for delete to authenticated
  using (public.es_personal());
-- (no hay política de insert: solo se puede crear con la función preinscribir)

-- 3. Funciones públicas (las únicas que ve quien no inició sesión) -------------------------------
create or replace function public.inscripcion_estado()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('abierta', c.abierta, 'ciclo', c.ciclo, 'mensaje', c.mensaje)
    from public.inscripcion_config c where c.id = 1;
$$;
revoke all on function public.inscripcion_estado() from public;
grant execute on function public.inscripcion_estado() to anon, authenticated;

create or replace function public.trayectos_para_inscripcion()
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', t.id,
           'nombre', t.nombre,
           'nro', coalesce(nullif(to_jsonb(t)->>'certificacion_oficial', ''), nullif(to_jsonb(t)->>'certificacion', '')),
           'horario', t.horario,
           'sede', coalesce(t.sede, 'sede'),
           'lugar', t.lugar_dictado,
           'inicio', t.fecha_inicio
         ) order by t.nombre), '[]'::jsonb)
    from public.trayectos t
    join public.inscripcion_config c on c.id = 1 and c.abierta
   where nullif(to_jsonb(t)->>'ciclo_lectivo', '')::integer = c.ciclo;
$$;
revoke all on function public.trayectos_para_inscripcion() from public;
grant execute on function public.trayectos_para_inscripcion() to anon, authenticated;

create or replace function public.preinscribir(p_trayecto bigint, p_datos jsonb, p_web text default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  cfg   public.inscripcion_config;
  dni_  text;
  ape   text;
  nom   text;
  mail  text;
  nuevo bigint;
  num   text;
begin
  -- trampa para robots: el campo "web" está oculto en la página y las personas lo dejan vacío
  if coalesce(p_web, '') <> '' then raise exception 'No se pudo enviar la preinscripción'; end if;

  select * into cfg from public.inscripcion_config where id = 1;
  if not found or not cfg.abierta then raise exception 'La inscripción está cerrada por el momento'; end if;

  if not exists (select 1 from public.trayectos t
                  where t.id = p_trayecto and nullif(to_jsonb(t)->>'ciclo_lectivo', '')::integer = cfg.ciclo) then
    raise exception 'El trayecto elegido no está disponible para este ciclo';
  end if;

  if p_datos is null or jsonb_typeof(p_datos) <> 'object' or length(p_datos::text) > 40000 then
    raise exception 'Datos inválidos';
  end if;

  dni_ := regexp_replace(coalesce(p_datos->>'dni', ''), '\D', '', 'g');
  ape  := upper(trim(coalesce(p_datos->>'apellido', '')));
  nom  := trim(coalesce(p_datos->>'nombre', ''));
  mail := nullif(lower(trim(coalesce(p_datos->>'email', ''))), '');
  if dni_ !~ '^[0-9]{6,9}$' then raise exception 'El DNI debe tener entre 6 y 9 números, sin puntos'; end if;
  if ape = '' or nom = '' then raise exception 'Completá apellido y nombre'; end if;
  if mail is not null and mail !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'El correo electrónico no es válido'; end if;

  -- freno contra envíos masivos
  if (select count(*) from public.preinscripciones where created_at > now() - interval '10 minutes') > 150 then
    raise exception 'Hay demasiadas solicitudes en este momento. Probá de nuevo en unos minutos';
  end if;

  if exists (select 1 from public.preinscripciones
              where trayecto_id = p_trayecto and dni = dni_ and estado <> 'rechazada') then
    raise exception 'Ya existe una preinscripción con ese DNI para este trayecto';
  end if;

  insert into public.preinscripciones (ciclo, trayecto_id, dni, apellido, nombre, email, datos)
  values (cfg.ciclo, p_trayecto, dni_, left(ape, 80), left(nom, 80), mail, p_datos)
  returning id into nuevo;

  num := 'P' || cfg.ciclo || '-' || lpad(nuevo::text, 4, '0');
  update public.preinscripciones set numero = num where id = nuevo;
  return jsonb_build_object('numero', num);
end $$;
revoke all on function public.preinscribir(bigint, jsonb, text) from public;
grant execute on function public.preinscribir(bigint, jsonb, text) to anon, authenticated;

-- Verificación: tienen que aparecer 2 tablas y 3 funciones
select 'tabla' as tipo, tablename::text as nombre from pg_tables where tablename in ('inscripcion_config', 'preinscripciones')
union all
select 'función', proname::text from pg_proc where proname in ('inscripcion_estado', 'trayectos_para_inscripcion', 'preinscribir');
