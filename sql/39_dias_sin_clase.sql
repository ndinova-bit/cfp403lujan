-- PASO 39 — DÍAS SIN CLASE (paro, jornada institucional, licencia, otros)
-- Ejecutar UNA vez en Supabase → SQL Editor (se puede repetir sin romper nada).
--
-- Reemplaza el diseño de sql/34_sin_clase.sql (estado 'sin_clase' en asistencias) por uno
-- más prolijo: una tabla aparte, sin insertar ninguna fila en asistencias por estudiante.
--
-- Cuando el docente (o administración/preceptoría) indica que un día NO se dictó clase:
--   · no se guarda asistencia de ningún estudiante para esa fecha + módulo,
--     por lo tanto NO cuenta como presente ni como ausente (no baja porcentajes
--     ni suma faltas seguidas);
--   · queda registrado el motivo, para el historial y la planilla mensual.
-- Si después se toma asistencia ese mismo día, la marca de "sin clase" se borra sola.
--
-- No se revierte el CHECK ni la columna "motivo" que agregó sql/34: quedan sin uso, no
-- rompen nada. guardar_asistencia() se redefine conservando TAL CUAL su chequeo de
-- permiso vigente en Luján (admin, preceptor o docente del trayecto), agregando solo el
-- borrado de dias_sin_clase.
-- =====================================================================================

create table if not exists public.dias_sin_clase (
  id          bigint generated by default as identity primary key,
  trayecto_id bigint not null references public.trayectos(id) on delete cascade,
  modulo_id   bigint references public.modulos(id) on delete cascade,   -- null = todos los módulos
  fecha       date   not null,
  motivo      text   not null,
  detalle     text   check (char_length(detalle) <= 300),
  creado_por  uuid   default auth.uid(),
  created_at  timestamptz not null default now(),
  constraint dias_sin_clase_motivo_check
    check (motivo in ('paro', 'jornada_institucional', 'licencia', 'otro'))
);

-- Un solo registro por trayecto + fecha + módulo (null cuenta como "todos los módulos")
create unique index if not exists dias_sin_clase_unico
  on public.dias_sin_clase (trayecto_id, fecha, coalesce(modulo_id, 0));

alter table public.dias_sin_clase enable row level security;

drop policy if exists dias_sin_clase_select on public.dias_sin_clase;
drop policy if exists dias_sin_clase_insert on public.dias_sin_clase;
drop policy if exists dias_sin_clase_update on public.dias_sin_clase;
drop policy if exists dias_sin_clase_delete on public.dias_sin_clase;

-- Mismo grupo que ve/toma asistencia en Luján: Dirección (es_admin, que incluye regente),
-- Preceptoría y Secretaría (es_personal/es_secretaria), el docente del trayecto, y el
-- estudiante inscripto (para verlo en su propio historial).
create policy dias_sin_clase_select on public.dias_sin_clase for select to authenticated
  using (public.es_admin() or public.es_personal() or public.es_secretaria()
         or public.es_docente_de(trayecto_id) or public.esta_inscripto(trayecto_id));
create policy dias_sin_clase_insert on public.dias_sin_clase for insert to authenticated
  with check (public.es_admin() or public.es_personal() or public.es_docente_de(trayecto_id));
create policy dias_sin_clase_update on public.dias_sin_clase for update to authenticated
  using (public.es_admin() or public.es_personal() or public.es_docente_de(trayecto_id))
  with check (public.es_admin() or public.es_personal() or public.es_docente_de(trayecto_id));
create policy dias_sin_clase_delete on public.dias_sin_clase for delete to authenticated
  using (public.es_admin() or public.es_personal() or public.es_docente_de(trayecto_id));

-- Marcar un día como "sin clase": borra la asistencia de esa fecha + módulo y guarda el motivo.
create or replace function public.marcar_dia_sin_clase(
  p_trayecto bigint, p_modulo bigint, p_fecha date, p_motivo text, p_detalle text default null
) returns void
language plpgsql security invoker set search_path = public as $$
begin
  if not (public.es_admin() or public.es_personal() or public.es_docente_de(p_trayecto)) then
    raise exception 'No tenés permiso para registrar días sin clase en este trayecto';
  end if;
  if p_motivo not in ('paro', 'jornada_institucional', 'licencia', 'otro') then
    raise exception 'Motivo no válido';
  end if;

  delete from public.asistencias
   where trayecto_id = p_trayecto and fecha = p_fecha and modulo_id is not distinct from p_modulo;

  delete from public.dias_sin_clase
   where trayecto_id = p_trayecto and fecha = p_fecha and modulo_id is not distinct from p_modulo;

  insert into public.dias_sin_clase (trayecto_id, modulo_id, fecha, motivo, detalle)
  values (p_trayecto, p_modulo, p_fecha, p_motivo, nullif(trim(coalesce(p_detalle, '')), ''));
end $$;

revoke all on function public.marcar_dia_sin_clase(bigint, bigint, date, text, text) from public, anon;
grant execute on function public.marcar_dia_sin_clase(bigint, bigint, date, text, text) to authenticated;

-- Quitar la marca (por si fue un error y ese día sí hubo clase)
create or replace function public.quitar_dia_sin_clase(
  p_trayecto bigint, p_modulo bigint, p_fecha date
) returns void
language plpgsql security invoker set search_path = public as $$
begin
  if not (public.es_admin() or public.es_personal() or public.es_docente_de(p_trayecto)) then
    raise exception 'No tenés permiso para modificar días sin clase en este trayecto';
  end if;
  delete from public.dias_sin_clase
   where trayecto_id = p_trayecto and fecha = p_fecha and modulo_id is not distinct from p_modulo;
end $$;

revoke all on function public.quitar_dia_sin_clase(bigint, bigint, date) from public, anon;
grant execute on function public.quitar_dia_sin_clase(bigint, bigint, date) to authenticated;

-- Al tomar asistencia de un día, se borra la marca de "sin clase" de esa fecha + módulo.
-- Esta es la versión VIGENTE de guardar_asistencia() en Luján (mismo chequeo de permiso:
-- admin, preceptor o docente del trayecto), con ese único agregado — no se tocan sus demás
-- chequeos ni columnas.
create or replace function public.guardar_asistencia(p_trayecto bigint, p_modulo bigint, p_fecha date, p_registros jsonb)
returns integer
language plpgsql
set search_path to 'public'
as $$
declare n integer;
begin
  if not (public.es_admin() or public.es_preceptor() or public.es_docente_de(p_trayecto)) then
    raise exception 'No tenés permiso para cargar asistencia en este trayecto';
  end if;
  delete from public.dias_sin_clase
   where trayecto_id = p_trayecto and fecha = p_fecha and modulo_id is not distinct from p_modulo;
  delete from public.asistencias
   where trayecto_id = p_trayecto and fecha = p_fecha and modulo_id is not distinct from p_modulo;
  insert into public.asistencias (trayecto_id, modulo_id, estudiante_user, fecha, estado, motivo)
  select p_trayecto, p_modulo, r->>'estudiante_user', p_fecha, lower(r->>'estado'), nullif(r->>'motivo', '')
    from jsonb_array_elements(p_registros) r
   where coalesce(r->>'estudiante_user', '') <> '';
  get diagnostics n = row_count;
  return n;
end $$;

-- Verificación: tienen que aparecer la tabla y las 3 funciones
select 'tabla' as tipo, tablename::text as nombre from pg_tables where tablename = 'dias_sin_clase'
union all
select 'función', proname::text from pg_proc
 where proname in ('marcar_dia_sin_clase', 'quitar_dia_sin_clase', 'guardar_asistencia');
