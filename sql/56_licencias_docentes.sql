-- PASO 56 — LICENCIAS DEL PERSONAL DOCENTE, FERIADOS Y CICLO LECTIVO
-- Ejecutar UNA vez en Supabase → SQL Editor (se puede repetir sin romper nada).
--
-- Registro de licencias administrativas, médicas y paros, que cargan y ven SOLO
-- Director (admin), Regente y Secretaría. Docentes, preceptores y estudiantes no
-- tienen acceso de ningún tipo (ni lectura).
--
--   · licencias            : una fila por período (desde/hasta) de cada docente.
--   · feriados             : nacionales, provinciales, municipales e institucionales
--                            (receso invernal, asuetos, etc.). No cuentan como hábiles.
--   · ciclo_lectivo_config : fecha de inicio y de fin del ciclo lectivo de cada año.
--   · docentes_para_licencias() : lista de docentes (solo para esos tres roles).
--
-- Importante: en "observaciones" NO se anotan diagnósticos. Para licencias médicas
-- alcanza con el período (y, si se quiere, el número de certificado).
-- =====================================================================================

-- Permiso común: Director, Regente (es_admin incluye regente) o Secretaría
create or replace function public.puede_gestionar_licencias()
returns boolean
language sql stable security definer
set search_path to 'public'
as $$ select public.es_admin() or public.es_secretaria(); $$;

-- ---------- LICENCIAS ----------
create table if not exists public.licencias (
  id            bigint generated by default as identity primary key,
  docente_dni   text   not null,
  tipo          text   not null check (tipo in ('administrativa', 'medica', 'paro')),
  articulo      text   check (char_length(articulo) <= 80),        -- artículo / código / N.º de certificado (opcional)
  desde         date   not null,
  hasta         date   not null,
  observaciones text   check (char_length(observaciones) <= 300),
  creado_por    uuid   default auth.uid(),
  created_at    timestamptz not null default now(),
  constraint licencias_rango_check check (hasta >= desde)
);
create index if not exists licencias_docente_idx on public.licencias (docente_dni, desde);
create index if not exists licencias_fechas_idx  on public.licencias (desde, hasta);

alter table public.licencias enable row level security;
drop policy if exists licencias_select on public.licencias;
drop policy if exists licencias_insert on public.licencias;
drop policy if exists licencias_update on public.licencias;
drop policy if exists licencias_delete on public.licencias;
create policy licencias_select on public.licencias for select to authenticated using (public.puede_gestionar_licencias());
create policy licencias_insert on public.licencias for insert to authenticated with check (public.puede_gestionar_licencias());
create policy licencias_update on public.licencias for update to authenticated
  using (public.puede_gestionar_licencias()) with check (public.puede_gestionar_licencias());
create policy licencias_delete on public.licencias for delete to authenticated using (public.puede_gestionar_licencias());

-- ---------- FERIADOS ----------
create table if not exists public.feriados (
  id         bigint generated by default as identity primary key,
  fecha      date not null,
  nombre     text not null check (char_length(nombre) <= 120),
  ambito     text not null check (ambito in ('nacional', 'provincial', 'municipal', 'institucional')),
  creado_por uuid default auth.uid(),
  created_at timestamptz not null default now(),
  unique (fecha, ambito)
);

alter table public.feriados enable row level security;
drop policy if exists feriados_select on public.feriados;
drop policy if exists feriados_insert on public.feriados;
drop policy if exists feriados_update on public.feriados;
