-- ---------- LISTA DE DOCENTES (para el selector) ----------
-- Los tres roles pueden no tener lectura directa de profiles; esta función devuelve
-- solo DNI, apellido y nombre de los docentes activos, y solo a quienes corresponde.
create or replace function public.docentes_para_licencias()
returns table (dni text, apellido text, nombre text)
language sql stable security definer
set search_path to 'public'
as $$
  select p.dni, p.apellido, p.nombre
  from public.profiles p
  where public.puede_gestionar_licencias()
    and lower(p.rol::text) = 'docente'
    and upper(coalesce(p.estado, 'ACTIVO')) = 'ACTIVO'
  order by p.apellido, p.nombre;
$$;

revoke all on function public.docentes_para_licencias() from public, anon;
grant execute on function public.docentes_para_licencias() to authenticated;
revoke all on function public.puede_gestionar_licencias() from public, anon;
grant execute on function public.puede_gestionar_licencias() to authenticated;

