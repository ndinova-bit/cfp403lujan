-- ---------- CICLO LECTIVO ----------
create table if not exists public.ciclo_lectivo_config (
  anio       integer primary key,
  inicio     date not null,
  fin        date not null,
  updated_at timestamptz not null default now(),
  constraint ciclo_rango_check check (fin >= inicio)
